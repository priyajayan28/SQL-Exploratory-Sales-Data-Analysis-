--Explore all objects in the database
select * from INFORMATION_SCHEMA.TABLES	

--Explore all columns in the database
select * from INFORMATION_SCHEMA.COLUMNS
where TABLE_NAME='dim_customers'

--Explore all countries our customers come from
select distinct country 
from dim_customers

--Explore all categories
select distinct category,subcategory,product_name 
from dim_products

--Find the date of first and last order
select min(order_date) as first_order_date, 
max(order_date) as last_order_date ,
DATEDIFF(year,min(order_date),max(order_date)) as order_range
from fact_sales


--Find the youngest and oldest customer
select min(birthdate) as oldest_birthdate,
DATEDIFF(year,min(birthdate),getdate()) as oldest_age,
max(birthdate) as youngest_birthdate,
DATEDIFF(year,max(birthdate),getdate()) as youngest_age from dim_customers

--Find the Total Sales
select sum(sales_amount) as Total_Sales
from fact_sales

--Find how many items are sold
select sum(quantity) as Total_quantity
from fact_sales

--Find the average selling price
select avg(price) as Average_price
from fact_sales

--Find the total number of orders
select count(order_number) as Total_order
from fact_sales
select count(distinct order_number) as Total_order
from fact_sales

--Find the total number of products
select count(product_key) as Total_products
from dim_products
select count(distinct product_key) as Total_products
from dim_products

--Find total number of customers
select count(customer_key) as Total_customers
from dim_customers

--Find the total number of customers that has placed an order
select count(distinct customer_key) as Total_customers
from fact_sales

--Generate a Report that shows all key metrics of the business
select 'Total Sales' as measure_name,sum(sales_amount) as measure_value from fact_sales
union all
select 'Total Quantity' as measure_name,sum(quantity) as measure_value from fact_sales
union all
select 'Average Price' as measure_name,avg(price) as measure_value from fact_sales
union all
select 'Total order' as measure_name,count(distinct order_number) as measure_value from fact_sales
union all
select 'Total Products' as measure_name,count(product_key) as measure_value from dim_products
union all
select 'Total Customers' as measure_name,count(customer_key) as measure_value from dim_customers

--find total number of customers by country
select country,count(customer_key) as Total_customers
from dim_customers
group by country
order by Total_customers desc

--find total number of customers by gender
select gender,count(customer_key) as Total_customers
from dim_customers
group by gender
order by Total_customers desc

--find totalproducts by category
select category,count(distinct product_key) as Total_products
from dim_products
group by category
order by Total_products desc

--find the average cost in each category
select category,avg(cost) as average_cost
from dim_products
group by category
order by average_cost desc

--total revenue generated for each category
select p.category,sum(s.sales_amount) as total_revenue
from fact_sales s
left join dim_products p
on p.product_key=s.product_key
group by p.category
order by total_revenue desc

--total revenue generated by each customer
select c.customer_key,c.first_name,c.last_name,sum(s.sales_amount) as total_revenue
from fact_sales s
left join dim_customers c
on c.customer_key=s.customer_key
group by c.customer_key,c.first_name,c.last_name
order by total_revenue desc

--what is the distribution of items sold across countries
select c.country,sum(s.quantity) as total_sold_item
from fact_sales s
left join dim_customers c on s.customer_key=c.customer_key
group by c.country
order by total_sold_item desc

--which 5 products generate the highest revenue
select top 5 p.product_name,sum(s.sales_amount) as total_revenue
from fact_sales s
left join dim_products p
on p.product_key=s.product_key
group by p.product_name
order by total_revenue desc

--what are the 5 worst performing products in terms of sales
select top 5 p.product_name,sum(s.sales_amount) as total_revenue
from fact_sales s
left join dim_products p
on p.product_key=s.product_key
group by p.product_name
order by total_revenue asc
